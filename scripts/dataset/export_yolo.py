"""Export records + split into an Ultralytics/YOLO-style dataset (also consumed by the FGD trainers).

  dataset/processed/yolo[_<tag>]/images/{train,val,test}/*.jpg
                                /labels/{train,val,test}/*.txt     ->  0 xc yc w h  (normalised)
                                anpr_detect.yaml, manifest.json

Images are down-scaled so max side <= --max-side (boxes are normalised, so labels are unaffected).
--include-auto adds reviewed/accepted auto labels (pool images) to TRAIN only.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

import cv2
import numpy as np

sys.path.insert(0, str(Path(__file__).parent))
from common import ANNOT, PROCESSED, ROOT, SPLITS, imread, read_jsonl  # noqa: E402


def export_one(rec: dict, split: str, out: Path, max_side: int) -> tuple[str, int]:
    img = imread(ROOT / rec["path"])
    if img is None:
        return rec["id"], 0
    h, w = img.shape[:2]
    s = min(1.0, max_side / max(h, w))
    if s < 1.0:
        img = cv2.resize(img, (round(w * s), round(h * s)), interpolation=cv2.INTER_AREA)
    H, W = img.shape[:2]
    ok, buf = cv2.imencode(".jpg", img, [cv2.IMWRITE_JPEG_QUALITY, 92])
    if not ok:
        return rec["id"], 0
    (out / "images" / split / f"{rec['id']}.jpg").write_bytes(buf.tobytes())
    lines = []
    for x1, y1, x2, y2 in rec["boxes"]:
        x1, x2 = x1 / w, x2 / w  # original-frame fractions
        y1, y2 = y1 / h, y2 / h
        lines.append(f"0 {(x1 + x2) / 2:.6f} {(y1 + y2) / 2:.6f} {x2 - x1:.6f} {y2 - y1:.6f}")
    (out / "labels" / split / f"{rec['id']}.txt").write_text("\n".join(lines) + ("\n" if lines else ""))
    return rec["id"], len(lines)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--split", default="v1")
    ap.add_argument("--max-side", type=int, default=1280)
    ap.add_argument("--include-auto", action="store_true")
    ap.add_argument("--manual-only-indian", action="store_true", help="drop external-domain images from train")
    ap.add_argument("--tag", default="")
    a = ap.parse_args()

    sp = json.loads((SPLITS / f"split_{a.split}.json").read_text())["split"]
    recs = read_jsonl(PROCESSED / "records_labeled.jsonl")
    if a.include_auto:
        auto = PROCESSED / "records_auto.jsonl"
        if not auto.exists():
            sys.exit("records_auto.jsonl missing - run auto_annotate.py first")
        recs += [r for r in read_jsonl(auto) if r["label_source"] in ("auto_accepted", "auto_reviewed")]
    out = PROCESSED / ("yolo" + (f"_{a.tag}" if a.tag else ""))
    for s in ("train", "val", "test"):
        (out / "images" / s).mkdir(parents=True, exist_ok=True)
        (out / "labels" / s).mkdir(parents=True, exist_ok=True)
    jobs = []
    for r in recs:
        s = sp.get(r["id"])
        if s == "pool":
            s = "train"  # auto-labelled pool never enters val/test
        if s not in ("train", "val", "test"):
            continue
        if a.manual_only_indian and r["domain"] != "indian" and s == "train":
            continue
        jobs.append((r, s))
    with ThreadPoolExecutor(8) as ex:
        res = list(ex.map(lambda j: export_one(j[0], j[1], out, a.max_side), jobs))
    bad = [i for i, n in res if n == 0]
    counts: dict[str, dict[str, int]] = {}
    for (r, s), (_, n) in zip(jobs, res):
        c = counts.setdefault(s, {"images": 0, "plates": 0})
        if n:
            c["images"] += 1
            c["plates"] += n
    cfg = (f"# Generated by export_yolo.py - do not edit\npath: {out.relative_to(ROOT).as_posix()}\n"
           "train: images/train\nval: images/val\ntest: images/test\nnames:\n  0: license_plate\n")
    (out / "anpr_detect.yaml").write_text(cfg)
    h = hashlib.sha256(json.dumps(sorted(r["id"] + sp.get(r["id"], "") for r, _ in jobs)).encode()).hexdigest()[:16]
    (out / "manifest.json").write_text(json.dumps({
        "split_version": a.split, "max_side": a.max_side, "include_auto": a.include_auto, "counts": counts,
        "unwritable": bad, "content_hash": h}, indent=1))
    print(json.dumps({"out": str(out), "counts": counts, "unwritable": len(bad), "hash": h}, indent=1))


if __name__ == "__main__":
    main()
